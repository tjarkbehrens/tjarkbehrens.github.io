#!/usr/bin/env python3
"""Draw the faint contour lines around the portrait (writes assets/topo.js).

Optional: only needed for a different terrain. Requires numpy and scikit-image.
    python3 tools/make_contours.py --seed 7
"""
import argparse, json, pathlib
import numpy as np
from skimage import measure

ap = argparse.ArgumentParser()
ap.add_argument("--seed", type=int, default=7)
rng = np.random.default_rng(ap.parse_args().seed)

W, H, STEP = 640, 520, 2.0
CX, CY = 180, 250  # summit = portrait centre; style.css positions the drawing to match
X, Y = np.meshgrid(np.arange(0, W + STEP, STEP), np.arange(0, H + STEP, STEP))

def bump(x0, y0, sx, sy, amp, rot=0.0):
    c, s = np.cos(rot), np.sin(rot)
    u, v = c * (X - x0) + s * (Y - y0), -s * (X - x0) + c * (Y - y0)
    return amp * np.exp(-(u**2 / (2 * sx**2) + v**2 / (2 * sy**2)))

h = bump(CX, CY, 150, 120, 1.0, 0.35)                 # the hill under the portrait
h += bump(CX + 210, CY - 140, 95, 70, 0.45, -0.5)     # a shoulder to the upper right
h += bump(CX + 60, CY + 230, 160, 55, 0.30, 0.25)     # a low ridge below
h -= bump(CX + 125, CY + 130, 55, 42, 0.20, 0.2)      # a shallow hollow with a small marsh
for _ in range(14):                                   # gentle wobble, like real terrain
    fx, fy = rng.uniform(0.006, 0.02, 2); ph = rng.uniform(0, 2 * np.pi, 2)
    h += rng.uniform(0.008, 0.02) * np.sin(fx * X + ph[0]) * np.cos(fy * Y + ph[1])

reg, idx = [], []
for i, level in enumerate(np.linspace(0.06, 0.98, 24)):
    for c in measure.find_contours(h, level):
        pts = measure.approximate_polygon(c[:, ::-1] * STEP, tolerance=0.45)
        if len(pts) < 6 or (np.ptp(pts[:, 0]) < 14 and np.ptp(pts[:, 1]) < 14):
            continue
        d = "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + ("Z" if np.allclose(pts[0], pts[-1]) else "")
        (idx if i % 5 == 4 else reg).append(f'<path d="{d}"/>')  # every 5th line is an index contour

def marsh(x, y):  # the map symbol for marsh: a water line with a tuft of reeds
    return (f'<path d="M{x-7:.1f} {y:.1f}h14"/>'
            f'<path d="M{x-1.8:.1f} {y-1:.1f}l-2 -5M{x:.1f} {y-1:.1f}v-6M{x+1.8:.1f} {y-1:.1f}l2 -5"/>')
spots = [(105, 122), (135, 138), (115, 157), (150, 112), (88, 146)]
marshes = "".join(marsh(CX + dx, CY + dy) for dx, dy in spots)

svg = (f'<svg class="topo" viewBox="0 0 {W} {H}" aria-hidden="true" focusable="false">'
       f'<g class="topo-reg">{"".join(reg)}</g><g class="topo-idx">{"".join(idx)}</g>'
       f'<g class="topo-marsh">{marshes}</g></svg>')
out = pathlib.Path(__file__).resolve().parent.parent / "assets" / "topo.js"
out.write_text("// Generated by tools/make_contours.py. To remove the lines, delete this file and its <script> tag.\n"
               f'(function () {{ var el = document.getElementById("topo"); if (el) el.innerHTML = {json.dumps(svg)}; }})();\n')
print(f"wrote {out} ({out.stat().st_size // 1024} KB)")
